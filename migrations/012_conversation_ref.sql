-- =============================================================================
-- 012_conversation_ref.sql
--
-- A readable reference for each conversation, next to its UUID - e.g.
-- PATIENT_ADMIN-1042. See CLAUDE.md Decision 20.
--
--   conversations.conversation_number  one number for the whole bridge, from
--                                      conversation_number_seq. Shared by all
--                                      topics, so a topic's numbers have gaps.
--   conversations.conversation_ref     '<topic_code>-<conversation_number>',
--                                      generated by Postgres. It never changes,
--                                      because a conversation's topic can't.
--
-- conversation_id stays the primary key and the only way to identify a
-- conversation on POST /api/v1/events. The ref is for people.
--
-- Existing conversations are numbered in the order they were created. The
-- updated_at trigger is paused meanwhile, so numbering them doesn't count as
-- activity (lists sort by updated_at).
--
-- Run with: psql "$DATABASE_URL" -f migrations/012_conversation_ref.sql
-- =============================================================================

BEGIN;

CREATE SEQUENCE conversation_number_seq AS BIGINT;

ALTER TABLE conversations ADD COLUMN conversation_number BIGINT;

ALTER TABLE conversations DISABLE TRIGGER trg_conversations_updated_at;

UPDATE conversations c
SET conversation_number = numbered.n
FROM (
    SELECT conversation_id, row_number() OVER (ORDER BY created_at, conversation_id) AS n
    FROM conversations
) numbered
WHERE numbered.conversation_id = c.conversation_id;

ALTER TABLE conversations ENABLE TRIGGER trg_conversations_updated_at;

SELECT setval('conversation_number_seq', COALESCE(MAX(conversation_number), 0) + 1, false)
FROM conversations;

ALTER TABLE conversations
    ALTER COLUMN conversation_number SET DEFAULT nextval('conversation_number_seq'),
    ALTER COLUMN conversation_number SET NOT NULL,
    ADD CONSTRAINT conversations_conversation_number_key UNIQUE (conversation_number);

ALTER SEQUENCE conversation_number_seq OWNED BY conversations.conversation_number;

ALTER TABLE conversations
    ADD COLUMN conversation_ref TEXT
        GENERATED ALWAYS AS (topic_code || '-' || conversation_number::text) STORED;

ALTER TABLE conversations
    ADD CONSTRAINT conversations_conversation_ref_key UNIQUE (conversation_ref);

COMMIT;
